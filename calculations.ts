//加算関数（add）：2つの数値を引数として受け取り、その和を返す
function add(a:number, b:number) :number{
    return a + b;
  };
  
  add(1,2);
  
  console.log(add(1,2));

//減算関数（subtract）：2つの数値を引数として受け取り、その差を返す
function subtract(a:number, b:number) :number{
    return a + b;
  };
  
  subtract(1,2);
  
  console.log(subtract(1,2));



  